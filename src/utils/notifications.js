// Custom alert for login failure
export const loginAlert = () => {
  toast.error("It looks like you're not logged in, please login again!", {
    position: "top-right",
    autoClose: 5000,
    hideProgressBar: false,
    closeOnClick: true,
    pauseOnHover: true,
    draggable: true,
    progress: undefined,
  });
};

